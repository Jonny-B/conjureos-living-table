#!/usr/bin/env node
/**
 * Writes src/games/livingtable/table/adventures/data.ts: every adventures/*.md (README.md is the authoring guide and is left out)
 * inlined as text, so the table window carries the owner's adventures with it and parses them in the page.
 *
 *   node scripts/asset-bench/gen-adventures.mjs           write the module
 *   node scripts/asset-bench/gen-adventures.mjs --check   exit 1 when the written module is out of date (no write)
 *
 * `npm run bench` runs this first. The module is COMMITTED (the tests and the registry import it, so it cannot be a
 * gitignored build product); test/livingtable-bench-adventures.test.ts fails when it is stale.
 *
 * The generated text must never name the bench folder: a guard test fails when any file under src/ does.
 *
 * Line endings are normalised to LF so the output is the same on every checkout.
 */
import { mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, "..", "..");
const DIR = join(ROOT, "adventures");
const OUT = join(ROOT, "src", "games", "livingtable", "table", "adventures", "data.ts");

/** Files under adventures/ that are not adventures. */
const KEEP_OUT = new Set(["README.md"]);

export function buildModule() {
  const files = readdirSync(DIR)
    .filter((n) => n.toLowerCase().endsWith(".md") && !KEEP_OUT.has(n))
    .sort((a, b) => a.localeCompare(b));
  const entries = files.map((file) => {
    const text = readFileSync(join(DIR, file), "utf8").replace(/\r\n?/g, "\n");
    return `  { file: ${JSON.stringify(file)}, text: ${JSON.stringify(text)} },`;
  });
  return [
    "/**",
    " * GENERATED by gen-adventures.mjs from adventures/*.md (README.md left out). Do not edit by hand:",
    " * edit the adventure file and run `npm run bench`, which runs the generator first.",
    " * The table window parses each text in the page (parseAdventureMarkdown) and checks it (validateAdventure).",
    " */",
    'import type { AdventureFile } from "../host";',
    "",
    "export type { AdventureFile };",
    "",
    "export const ADVENTURE_FILES: readonly AdventureFile[] = [",
    ...entries,
    "];",
    "",
  ].join("\n");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const next = buildModule();
  if (process.argv.includes("--check")) {
    let now = "";
    try {
      now = readFileSync(OUT, "utf8").replace(/\r\n?/g, "\n");
    } catch {
      /* missing */
    }
    if (now !== next) {
      console.error("src/games/livingtable/table/adventures/data.ts is out of date. Run: node scripts/asset-bench/gen-adventures.mjs");
      process.exit(1);
    }
    console.log("adventures/data.ts is up to date");
  } else {
    mkdirSync(dirname(OUT), { recursive: true });
    writeFileSync(OUT, next, "utf8");
    console.log(`wrote ${OUT} (${next.length} bytes)`);
  }
}
