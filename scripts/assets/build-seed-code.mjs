/**
 * Emits a TypeScript module (to stdout) embedding the fantasy + sci-fi tile
 * libraries as plain data, for pasting into the ConjureOS repo's
 * games-db/index.ts (see that file's LIVING_TABLE_TEMPLATES constant and its
 * doc comment for why this lives in code, not a migration, mirroring the
 * Vault's level definitions in the same file).
 *
 * Not run automatically, not part of the app build: this is an authoring-time
 * tool, run by hand whenever the asset source in fantasy.ts/scifi.ts changes
 * and the embedded copy in games-db needs to catch up. It only reads
 * PALETTE/SPRITES, so its output is deterministic given those.
 *
 * Run: npx tsx scripts/assets/build-seed-code.mjs > /tmp/livingtable-assets.ts
 * then paste the output into games-db/index.ts by hand (a redeploy, not a
 * migration).
 */
import { PALETTE as FANTASY_PALETTE, SPRITES as FANTASY_SPRITES } from "./fantasy.ts";
import { PALETTE as SCIFI_PALETTE, SPRITES as SCIFI_SPRITES } from "./scifi.ts";

function paletteLiteral(palette) {
  return `[${palette.map(([r, g, b]) => `[${r},${g},${b}]`).join(",")}]`;
}

function pixelsLiteral(pixels) {
  return `[${pixels.map((row) => `[${row.join(",")}]`).join(",")}]`;
}

function spriteLiteral(s) {
  return (
    `{assetId:${JSON.stringify(s.assetId)},kind:${JSON.stringify(s.kind)},name:${JSON.stringify(s.name)},` +
    `size:${s.size},walkable:${s.walkable},pixels:${pixelsLiteral(s.pixels)}}`
  );
}

function templateLiteral(palette, sprites) {
  return `{\n  palette: ${paletteLiteral(palette)},\n  sprites: [\n    ${sprites.map(spriteLiteral).join(",\n    ")},\n  ],\n}`;
}

console.log(
  `// Generated by scripts/assets/build-seed-code.mjs from fantasy.ts / scifi.ts. Paste over the\n` +
    `// existing LIVING_TABLE_TEMPLATES constant in games-db/index.ts, then redeploy the function.\n` +
    `// Not applied automatically; this is not a migration and never touches the database.\n` +
    `const LIVING_TABLE_TEMPLATES: Record<"fantasy" | "scifi", { palette: [number, number, number][]; sprites: LtSprite[] }> = {\n` +
    `  fantasy: ${templateLiteral(FANTASY_PALETTE, FANTASY_SPRITES)},\n` +
    `  scifi: ${templateLiteral(SCIFI_PALETTE, SCIFI_SPRITES)},\n` +
    `};\n`,
);
