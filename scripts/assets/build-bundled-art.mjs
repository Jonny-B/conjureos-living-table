/**
 * build-bundled-art.mjs: write src/games/livingtable/table/host/bundledArt.ts, the hand-drawn picture library as
 * data the game can import.
 *
 * Why this exists. The game's art comes from games-db (`ltAssetManifest`), which holds a copy of scripts/assets/fantasy.ts
 * that is pasted in by hand (build-seed-code.mjs). The table window plays the adventures in adventures/*.md, and those
 * were written against the authoring library. If the deployed copy is behind (a prop or token an adventure names is not
 * in it yet), the window would draw nothing for that id. gameArt.ts (the table's game-side art host) checks the loaded
 * manifest against what the adventures need and, when it falls short, draws from THIS copy instead.
 *
 * Why it is a generated module and not an import. scripts/ is not under src/ (the game's typecheck and bundle never see
 * it, DESIGN.md keeps the library out of the app on purpose), so src cannot import fantasy.ts. This writes the part the
 * fallback needs into src as plain data.
 *
 * Size. Only the fantasy template (the one the launch game plays, and the one every adventure is written for). Each
 * sprite's pixel grid is packed to one string: a palette index plus one (so the transparent -1 is 0) as one base64
 * character, runs of four or more as "<char>*<count>;", rows joined by "|". The decoder is `decodeBundledPixels` in
 * gameArt.ts, and test/livingtable-table-host.test.ts proves the round trip against fantasy.ts, so the two cannot drift
 * apart unnoticed.
 *
 *   npx tsx scripts/assets/build-bundled-art.mjs           write the module
 *   npx tsx scripts/assets/build-bundled-art.mjs --check   exit 1 when the written module is out of date (no write)
 *
 * Run it whenever fantasy.ts changes. The module is COMMITTED (src imports it); the test fails when it is stale.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { PALETTE as FANTASY_PALETTE, SPRITES as FANTASY_SPRITES } from "./fantasy.ts";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(HERE, "..", "..");
const OUT = join(ROOT, "src", "games", "livingtable", "table", "host", "bundledArt.ts");

const ALPHABET = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
const MIN_RUN = 4;

function packRow(row) {
  let out = "";
  let i = 0;
  while (i < row.length) {
    const v = row[i];
    if (!Number.isInteger(v) || v < -1 || v + 1 >= ALPHABET.length) throw new Error(`pixel value ${v} cannot be packed`);
    let n = 1;
    while (i + n < row.length && row[i + n] === v) n += 1;
    const c = ALPHABET[v + 1];
    out += n >= MIN_RUN ? `${c}*${n};` : c.repeat(n);
    i += n;
  }
  return out;
}

export function packPixels(rows) {
  return rows.map(packRow).join("|");
}

function spriteLiteral(s) {
  return (
    `{ assetId: ${JSON.stringify(s.assetId)}, kind: ${JSON.stringify(s.kind)}, name: ${JSON.stringify(s.name)}, ` +
    `size: ${s.size}, walkable: ${s.walkable}, px: ${JSON.stringify(packPixels(s.pixels))} }`
  );
}

export function buildModule() {
  const palette = `[${FANTASY_PALETTE.map(([r, g, b]) => `[${r}, ${g}, ${b}]`).join(", ")}]`;
  return [
    "/**",
    " * GENERATED by scripts/assets/build-bundled-art.mjs from scripts/assets/fantasy.ts. Do not edit by hand:",
    " * change fantasy.ts and run `npx tsx scripts/assets/build-bundled-art.mjs`.",
    " *",
    " * The hand-drawn fantasy library, packed, for gameArt.ts to fall back on when the games-db manifest is missing an",
    " * id the adventures use. `px` is the sprite's pixel grid packed to a string (see the generator for the format and",
    " * decodeBundledPixels in gameArt.ts for the way back).",
    " */",
    "export interface BundledSprite {",
    "  assetId: string;",
    '  kind: "tile" | "token" | "prop";',
    "  name: string;",
    "  /** The sprite's width and tile footprint (height is the decoded grid's own row count). */",
    "  size: number;",
    "  walkable: boolean;",
    "  /** The pixel grid, packed. */",
    "  px: string;",
    "}",
    "",
    "export interface BundledLibrary {",
    "  palette: [number, number, number][];",
    "  sprites: BundledSprite[];",
    "}",
    "",
    "export const BUNDLED_ART: { fantasy: BundledLibrary } = {",
    "  fantasy: {",
    `    palette: ${palette},`,
    "    sprites: [",
    ...FANTASY_SPRITES.map((s) => `      ${spriteLiteral(s)},`),
    "    ],",
    "  },",
    "};",
    "",
  ].join("\n");
}

const isMain = process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const text = buildModule();
  if (process.argv.includes("--check")) {
    let current = "";
    try {
      current = readFileSync(OUT, "utf8").replace(/\r\n?/g, "\n");
    } catch {
      current = "";
    }
    if (current !== text) {
      console.error("[bundled-art] src/games/livingtable/table/host/bundledArt.ts is out of date. Run: npx tsx scripts/assets/build-bundled-art.mjs");
      process.exit(1);
    }
    console.log("[bundled-art] up to date");
  } else {
    writeFileSync(OUT, text, "utf8");
    console.log(`[bundled-art] wrote ${OUT} (${(text.length / 1024).toFixed(0)} KB, ${FANTASY_SPRITES.length} sprites)`);
  }
}
